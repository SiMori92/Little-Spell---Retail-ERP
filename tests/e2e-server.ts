import 'server-only';
import { spawn } from 'node:child_process';
import { mkdir, mkdtemp } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { initializeWorkspace } from '../src/server/initialize';
import { RunStore } from '../src/server/store';
import { journalCandidate } from './helpers';
import { projectMasters } from '../src/domain/master-projection';
import { planProcurement } from '../src/domain/procurement';
await mkdir(resolve('.tools/e2e'),{recursive:true});
const directory=await mkdtemp(join(resolve('.tools/e2e'),'workspace-'));
process.env.ERP_DATA_DIR=directory;
await initializeWorkspace(directory);
await new RunStore(directory).execute(()=>journalCandidate({idempotencyKey:'e2e-journal'}));
const store=new RunStore(directory);
const masters=projectMasters(await store.read());
await store.execute(runs=>planProcurement({action:'count',occurredOn:'2025-12-01',idempotencyKey:'e2e-counted-stock',founderConfirmed:true,record:{countedAt:'2025-12-01',evidenceRef:'synthetic-browser-test-stock',lines:masters.products.map(({record})=>({sku:record.sku,qtyPieces:record.productType==='packaging'?'0':'1000',agreedUnitCostTwd:record.productType==='packaging'?'0.0000':'1.0000',condition:'sellable'}))}},runs));
const child=spawn(process.execPath,['--import','tsx','--conditions=react-server','scripts/start.ts','dev'],{stdio:'inherit',env:process.env});
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>child.kill(signal));
child.on('exit',code=>{process.exitCode=code??1;});
